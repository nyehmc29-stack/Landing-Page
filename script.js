function updateGameInputFields(game) {
  const config = gameInputConfig[game] || gameInputConfig["Mobile Legends"];
  const playerLabel = document.getElementById("playerIdLabel");
  const playerInput = document.getElementById("playerId");
  const serverWrapper = document.getElementById("serverFieldWrapper");
  const serverLabel = document.querySelector('label[for="serverId"]');
  const serverInput = document.getElementById("serverId");

  if (playerLabel) playerLabel.textContent = config.label;
  if (playerInput) {
    playerInput.placeholder = config.placeholder;
    playerInput.autocomplete = "off";
  }
  if (serverWrapper) serverWrapper.style.display = config.server ? "" : "none";
  if (serverLabel && config.server) serverLabel.textContent = config.serverLabel;
  if (serverInput) {
    serverInput.placeholder = config.serverPlaceholder || "";
    serverInput.required = Boolean(config.server);
    if (!config.server) serverInput.value = "";
  }
}

function rupiah(value) {
  return new Intl.NumberFormat("id-ID", {
    style: "currency",
    currency: "IDR",
    maximumFractionDigits: 0
  }).format(value);
}

function showToast(message) {
  if (!toast) return;

  toast.textContent = message;
  toast.classList.add("show");

  clearTimeout(window.toastTimer);
  window.toastTimer = setTimeout(() => {
    toast.classList.remove("show");
  }, 2800);
}

function hideBrokenImage(img) {
  if (!img) return;

  img.addEventListener("error", () => {
    img.style.display = "none";
  }, { once: true });

  if (img.complete && img.naturalWidth === 0) {
    img.style.display = "none";
  }
}

