function renderNominals(game) {
  if (!gameData[game] || !nominalGrid || !selectedGame || !nominalLabel || !totalPrice) {
    return;
  }

  const data = gameData[game];

  selectedGame.textContent = game;
  updateGameInputFields(game);
  nominalLabel.textContent = `Pilih Nominal ${data.currency}`;
  nominalGrid.innerHTML = "";

  let globalIndex = 0;
  let firstItemPrice = 0;

  data.sections.forEach(section => {
    const sectionTitle = document.createElement("div");
    sectionTitle.className = "nominal-section-title";
    sectionTitle.textContent = section.title;
    nominalGrid.appendChild(sectionTitle);

    const sectionGrid = document.createElement("div");
    sectionGrid.className = "nominal-section-grid";

    section.items.forEach(item => {
      const isFirst = globalIndex === 0;

      if (isFirst) {
        firstItemPrice = item[1];
      }

      const button = document.createElement("button");
      button.type = "button";
      button.className = `nominal ${isFirst ? "selected" : ""}`;

      const discountBadge = item[3]
        ? `<span class="disc-badge">${item[3]}</span>`
        : "";

      const oldPriceHtml = item[2] > 0
        ? `<small class="old-price">${rupiah(item[2])}</small>`
        : "";

      button.innerHTML = `
        <div class="nominal-info">
          <strong>${item[0]}</strong>
          <div class="price-wrap">
            <span class="new-price">${rupiah(item[1])}</span>
            ${discountBadge}
          </div>
          ${oldPriceHtml}
        </div>
        <div class="card-icon-corner">
          <img
            src="${data.icon}"
            alt="${data.currency}"
            width="24"
            height="24"
            style="object-fit: contain;"
          >
        </div>
      `;

      const icon = button.querySelector("img");
      hideBrokenImage(icon);

      button.addEventListener("click", () => {
        document.querySelectorAll(".nominal").forEach(el => {
          el.classList.remove("selected");
        });

        button.classList.add("selected");
        currentPrice = item[1];
        promoApplied = false;
        batasPromo = 1;
        totalPrice.textContent = rupiah(currentPrice);

        if (kodePromoInput) {
          kodePromoInput.value = "";
        }
      });

      sectionGrid.appendChild(button);
      globalIndex++;
    });

    nominalGrid.appendChild(sectionGrid);
  });

  currentPrice = firstItemPrice;
  promoApplied = false;
  batasPromo = 1;
  totalPrice.textContent = rupiah(currentPrice);

  if (kodePromoInput) {
    kodePromoInput.value = "";
  }
}

