if (testimoniSlider && prevTestimoni && nextTestimoni) {
  const cards = Array.from(testimoniSlider.querySelectorAll(".testimoni-card"));
  let currentTestimoniIndex = 0;

  function getMaxIndex() {
    return Math.max(0, cards.length - 1);
  }

  function updateTestimoniSlide() {
    const maxIndex = getMaxIndex();

    currentTestimoniIndex = Math.min(
      Math.max(0, currentTestimoniIndex),
      maxIndex
    );

    testimoniSlider.style.transform =
      `translate3d(-${currentTestimoniIndex * 100}%, 0, 0)`;

    if (sliderControls) {
      sliderControls.querySelectorAll(".dot").forEach((dot, index) => {
        dot.classList.toggle("active", index === currentTestimoniIndex);
      });
    }

    prevTestimoni.disabled = currentTestimoniIndex === 0;
    nextTestimoni.disabled = currentTestimoniIndex === maxIndex;
  }

  nextTestimoni.addEventListener("click", () => {
    if (currentTestimoniIndex < getMaxIndex()) {
      currentTestimoniIndex++;
      updateTestimoniSlide();
    }
  });

  prevTestimoni.addEventListener("click", () => {
    if (currentTestimoniIndex > 0) {
      currentTestimoniIndex--;
      updateTestimoniSlide();
    }
  });

  if (sliderControls) {
    sliderControls.querySelectorAll(".dot").forEach(dot => {
      dot.addEventListener("click", () => {
        const targetIndex = Number(dot.dataset.index);

        if (Number.isInteger(targetIndex)) {
          currentTestimoniIndex = targetIndex;
          updateTestimoniSlide();
        }
      });
    });
  }

  let touchStartX = 0;

  testimoniSlider.addEventListener("touchstart", event => {
    touchStartX = event.changedTouches[0].clientX;
  }, { passive: true });

  testimoniSlider.addEventListener("touchend", event => {
    const touchEndX = event.changedTouches[0].clientX;
    const distance = touchStartX - touchEndX;

    if (Math.abs(distance) > 40) {
      if (distance > 0 && currentTestimoniIndex < getMaxIndex()) {
        currentTestimoniIndex++;
      } else if (distance < 0 && currentTestimoniIndex > 0) {
        currentTestimoniIndex--;
      }

      updateTestimoniSlide();
    }
  }, { passive: true });

  window.addEventListener("resize", updateTestimoniSlide);
  updateTestimoniSlide();
}

document.addEventListener("DOMContentLoaded", () => {
  const revealElements = document.querySelectorAll(
    ".section, .hero-content, .hero-visual, .promo, footer"
  );

  revealElements.forEach(el => el.classList.add("reveal"));

  if (!("IntersectionObserver" in window)) {
    revealElements.forEach(el => el.classList.add("active"));
    return;
  }

  const revealObserver = new IntersectionObserver((entries, observer) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add("active");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.15 });

  revealElements.forEach(el => revealObserver.observe(el));
});

document.addEventListener("DOMContentLoaded", () => {
  const counters = document.querySelectorAll(".trust-row .counter");
  const trustRowElement = document.querySelector(".trust-row");

  if (!counters.length || !trustRowElement) return;

  let animated = false;

  function runCounter() {
    if (animated) return;
    animated = true;

    counters.forEach(counter => {
      const target = parseFloat(counter.getAttribute("data-target")) || 0;
      const suffix = counter.getAttribute("data-suffix") || "";
      const decimal = counter.hasAttribute("data-decimal") ? 1 : 0;
      const duration = 2000;
      let startTime = null;

      function updateCount(currentTime) {
        if (startTime === null) startTime = currentTime;

        const progress = currentTime - startTime;
        const ratio = Math.min(progress / duration, 1);
        const current = target * ratio;

        counter.textContent = current.toFixed(decimal) + suffix;

        if (ratio < 1) {
          requestAnimationFrame(updateCount);
        } else {
          counter.textContent = target.toFixed(decimal) + suffix;
        }
      }

      requestAnimationFrame(updateCount);
    });
  }

  if (!("IntersectionObserver" in window)) {
    runCounter();
    return;
  }

  const observer = new IntersectionObserver((entries, obs) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        runCounter();
        obs.unobserve(entry.target);
      }
    });
  }, { threshold: 0.5 });

  observer.observe(trustRowElement);
});

